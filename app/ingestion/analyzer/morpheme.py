def extract_nouns(text: str) -> list[str]:
    tokens = _kiwi.tokenize(text)
    return [
        t.form
        for t in tokens
        if t.tag in ("NNG", "NNP") and t.form not in STOPWORDS and len(t.form) > 1
    ]
